import pandas as pd
import numpy as np
import shap
from catboost import CatBoostClassifier, Pool
from sklearn.feature_extraction.text import TfidfVectorizer
# 加载训练好的 CatBoost 模型
model = CatBoostClassifier()
model.load_model('mnt/trained_catboost_model_n.cbm')

# 获取训练时的特征列表
train_features = model.feature_names_

# 加载测试数据
test_data = pd.read_csv("dataset/test.csv")

# 移除标签列（如果存在）
if '人工审核结果' in test_data.columns:
    test_data = test_data.drop(['人工审核结果'], axis=1)

# 确保测试数据包含所有训练时的特征
for feature in train_features:
    if feature not in test_data.columns:
        print(f"添加缺失特征: {feature}")
        test_data[feature] = np.nan  # 填充默认值

# 提取正文的 TF-IDF 特征
tfidf = TfidfVectorizer(max_features=1000, ngram_range=(1, 2))
text_features = tfidf.fit_transform(test_data['正文'])
text_df = pd.DataFrame(text_features.toarray(), columns=tfidf.get_feature_names_out())

# 合并规则特征（若有）和文本特征
X_test = pd.concat([test_data[train_features], text_df], axis=1)


print("测试数据基本信息：")
X_test.info()

# 获取模型的文本特征（如果有）
text_features = ['正文'] if '正文' in train_features else []

# 获取模型的分类特征索引
cat_feature_indices = model.get_cat_feature_indices()

# 创建Pool对象，正确指定文本特征和分类特征
test_pool = Pool(
    data=X_test,
    cat_features=cat_feature_indices,
    text_features=text_features
)
# 计算 SHAP 交互值，识别对预测影响最大的短语
shap_interaction = shap.TreeExplainer(model).shap_interaction_values(test_pool)

# 可视化前10个重要的特征交互（示例）
shap.summary_plot(shap_interaction, X_test, feature_names=X_test.columns, plot_type="bar")


