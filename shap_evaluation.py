def explain_prediction(sample_index, shap_values, X_test, rule_feature_mapping, rule_explanation):
    """
    解释单个样本的预测结果
    """
    sample_shap_values = shap_values[sample_index]
    sample_features = X_test.iloc[sample_index]
    prediction = model.predict([sample_features.values])[0]

    explanation = f"预测结果: {'通过' if prediction == 1 else '不通过'}\n"
    important_features = []

    for rule, features in rule_feature_mapping.items():
        for feature in features:
            if feature in X_test.columns:
                shap_value = sample_shap_values[X_test.columns.get_loc(feature)]
                if abs(shap_value) > 0.05:
                    feature_explanation = rule_explanation.get(feature, feature)
                    direction = '正向' if shap_value > 0 else '负向'
                    important_features.append(f"{rule}中的{feature_explanation}有{direction}影响，SHAP 值: {shap_value:.2f}")

    if important_features:
        explanation += "主要影响因素:\n" + "\n".join(important_features)
    else:
        explanation += "各因素影响较小。"

    return explanation

